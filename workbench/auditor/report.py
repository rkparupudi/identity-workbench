"""Findings CSV and a self-contained HTML report."""
from __future__ import annotations

import csv
import html
import io
import json

from .guidance import remediation
from .rules import SEVERITY, SEVERITY_ORDER, TITLES

CSV_COLUMNS = ["finding_id", "severity", "type", "system", "username", "account_id",
               "employee_id", "person_name", "summary", "evidence"]


def findings_csv(findings: list[dict]) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(CSV_COLUMNS)
    for f in findings:
        writer.writerow([f.get("finding_id", ""), f["severity"], f["type"], f.get("system", ""),
                         f.get("username", ""), f.get("account_id", ""), f.get("employee_id", ""),
                         f.get("person_name", ""), f["summary"],
                         json.dumps(f.get("evidence", {}), sort_keys=True)])
    return buffer.getvalue()


def template_summary(stats: dict, counts_by_type: dict, counts_by_severity: dict,
                     skipped: dict) -> str:
    """Plain summary built only from computed numbers. Used when no model is configured."""
    total = sum(counts_by_type.values())
    matching = stats["matching"]
    systems = ", ".join(f"{name} ({count:,})" for name, count in stats["accounts_by_system"].items())
    parts = [
        f"This audit compared {stats['people']:,} HR records with {stats['accounts']:,} accounts "
        f"across {len(stats['accounts_by_system'])} system(s): {systems}.",
        f"{matching['matched']:,} accounts were matched to a person, {matching['review']:,} need "
        f"a human decision, and {matching['unmatched']:,} matched nobody.",
        f"The rules produced {total:,} findings: "
        + ", ".join(f"{counts_by_severity.get(s, 0):,} {s}" for s in SEVERITY_ORDER) + ".",
    ]
    critical = [t for t in counts_by_type if SEVERITY[t] == "critical"]
    if critical:
        parts.append("Start with the critical items: " + "; ".join(
            f"{counts_by_type[t]:,} {TITLES[t].lower()}" for t in critical) + ".")
    if skipped:
        parts.append(f"{len(skipped)} rule(s) were skipped because the files lacked the "
                     "columns they need; see the end of this report.")
    return " ".join(parts)


_CSS = """
body{font-family:Segoe UI,Helvetica,Arial,sans-serif;color:#1c1c1c;margin:32px auto;max-width:1040px;padding:0 20px;line-height:1.45}
h1{font-size:26px;margin-bottom:4px} h2{font-size:19px;margin-top:34px;border-bottom:1px solid #ddd;padding-bottom:6px}
h3{font-size:16px;margin-top:26px} .meta{color:#666;font-size:13px}
table{border-collapse:collapse;width:100%;font-size:13px;margin:10px 0}
th,td{border:1px solid #ddd;padding:6px 8px;text-align:left;vertical-align:top} th{background:#f5f5f3}
.sev{display:inline-block;padding:1px 8px;border-radius:10px;font-size:12px;font-weight:600}
.critical{background:#fbe4e4;color:#9b1c1c}.high{background:#fdeedd;color:#9a4a00}
.medium{background:#fbf3d0;color:#7a5d00}.low{background:#e8eef7;color:#2b4a7a}
.cards{display:flex;gap:12px;flex-wrap:wrap}.card{border:1px solid #ddd;border-radius:8px;padding:10px 16px;min-width:120px}
.card b{display:block;font-size:22px} .note{color:#666;font-size:13px} ul{margin:6px 0 6px 18px;padding:0}
"""


def _e(value) -> str:
    return html.escape("" if value is None else str(value))


def html_report(run_id: str, as_of: str, stats: dict, findings: list[dict], skipped: dict,
                summary_text: str | None = None, max_rows_per_type: int = 200,
                title: str = "Identity hygiene audit") -> str:
    by_type: dict[str, list[dict]] = {}
    by_sev: dict[str, int] = {}
    for f in findings:
        by_type.setdefault(f["type"], []).append(f)
        by_sev[f["severity"]] = by_sev.get(f["severity"], 0) + 1
    counts = {t: len(items) for t, items in by_type.items()}
    summary_text = summary_text or template_summary(stats, counts, by_sev, skipped)
    matching = stats["matching"]

    out = [f"<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'><title>{_e(title)}</title>"
           f"<style>{_CSS}</style></head><body>",
           f"<h1>{_e(title)}</h1>",
           f"<div class='meta'>Run {_e(run_id)} · data as of {_e(as_of)} · "
           "generated by Identity Workbench</div>",
           "<h2>Summary</h2>", f"<p>{_e(summary_text)}</p>", "<div class='cards'>"]
    for sev in SEVERITY_ORDER:
        out.append(f"<div class='card'><b>{by_sev.get(sev, 0):,}</b>"
                   f"<span class='sev {sev}'>{sev}</span></div>")
    out.append(f"<div class='card'><b>{matching['review']:,}</b>matches to review</div></div>")

    out.append("<h2>Findings by type</h2><table><tr><th>Finding</th><th>Severity</th>"
               "<th>Count</th></tr>")
    ordered = sorted(by_type, key=lambda t: (SEVERITY_ORDER.index(SEVERITY[t]), t))
    for t in ordered:
        out.append(f"<tr><td><a href='#{t}'>{_e(TITLES[t])}</a></td>"
                   f"<td><span class='sev {SEVERITY[t]}'>{SEVERITY[t]}</span></td>"
                   f"<td>{counts[t]:,}</td></tr>")
    out.append("</table>")

    for t in ordered:
        items = by_type[t]
        systems = sorted({f["system"] for f in items if f["system"]})
        out.append(f"<h3 id='{t}'>{_e(TITLES[t])} "
                   f"<span class='sev {SEVERITY[t]}'>{SEVERITY[t]}</span> · {len(items):,}</h3>")
        guide = remediation(t)
        out.append(f"<p>{_e(guide['risk'])}</p><b>What to do</b><ul>"
                   + "".join(f"<li>{_e(s)}</li>" for s in guide["steps"]) + "</ul>")
        for system in systems:
            steps = remediation(t, system)["platform_steps"]
            if steps:
                out.append(f"<b>In {_e(system)}</b><ul>"
                           + "".join(f"<li>{_e(s)}</li>" for s in steps) + "</ul>")
        out.append("<table><tr><th>ID</th><th>System</th><th>Account</th><th>Person</th>"
                   "<th>Detail</th></tr>")
        for f in items[:max_rows_per_type]:
            person = f.get("person_name") or ""
            if f.get("employee_id"):
                person = f"{person} ({f['employee_id']})" if person else f["employee_id"]
            out.append(f"<tr><td>{_e(f.get('finding_id'))}</td><td>{_e(f.get('system'))}</td>"
                       f"<td>{_e(f.get('username'))}</td><td>{_e(person)}</td>"
                       f"<td>{_e(f['summary'])}</td></tr>")
        out.append("</table>")
        if len(items) > max_rows_per_type:
            out.append(f"<p class='note'>Showing the first {max_rows_per_type:,} of "
                       f"{len(items):,}. The findings CSV has every row.</p>")

    out.append("<h2>How the data was read</h2><table><tr><th>File</th><th>Records</th>"
               "<th>Columns used</th><th>Columns ignored</th></tr>")
    record_counts = {"hr": stats["people"], **stats["accounts_by_system"]}
    for name, mapping in stats["mappings"].items():
        used = ", ".join(f"{src} → {field}" for field, src in mapping.items())
        ignored = ", ".join(stats["unmapped_columns"].get(name, [])) or "none"
        out.append(f"<tr><td>{_e(name)}</td><td>{record_counts.get(name, 0):,}</td>"
                   f"<td>{_e(used)}</td><td>{_e(ignored)}</td></tr>")
    out.append("</table>")
    methods = ", ".join(f"{count:,} by {name.replace('_', ' ')}"
                        for name, count in matching["matched_by"].items()) or "none"
    out.append(f"<p class='note'>Matched accounts: {methods}.</p>")

    if skipped:
        out.append("<h2>Rules that were skipped</h2><ul>")
        for rule, reason in skipped.items():
            out.append(f"<li><b>{_e(TITLES.get(rule, rule))}:</b> {_e(reason)}</li>")
        out.append("</ul>")
    out.append("<p class='note'>Findings come from deterministic rules over the supplied "
               "exports. Verify each one against the source system before acting.</p>"
               "</body></html>")
    return "".join(out)
